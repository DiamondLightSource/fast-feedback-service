TEST(BaselineIntegrator, MLTarget) {
    Vector3d a(
        -49.87873210808719,
        -15.20510152622829,
        -56.55306758976276
    );
    Vector3d b(
        53.86563471994483,
        22.38534427742018,
        -53.177943634990626
    );
    Vector3d c(
        26.968649257725442,
        -73.12672631215553,
        -2.196321822105007
    );
    gemmi::SpaceGroup sg(1);
    Crystal crystal(a,b,c,sg);
    MonochromaticBeam beam(0.622);
    Vector3d s0 = beam.get_s0();
    Matrix3d A = crystal.get_A_matrix();

    std::vector<double> intensities = {
        114.6045137 , 122.10428274, 146.56838453,  48.9823156};
    std::vector<Vector3d> covariances;
    covariances.push_back({5e-6, 4e-6, 3e-6});
    covariances.push_back({8e-6, 5e-6, 2e-6});
    covariances.push_back({2e-6, 4e-6, 1e-6});
    covariances.push_back({5e-6, 3e-6, 2e-6});
    std::vector<Eigen::Vector3i> miller_indices({
        {-11,  11, -10},
       {  1,  -1, -10},
       {  6,  -7,  -7},
       { 11, -14,  -9}});
    std::vector<Vector2d> mobs({
        {1.49227749e-08, -3.46996157e-08},
       {-2.76029632e-09, -1.90182410e-08},
       {2.75093813e-09, -1.22847130e-08},
       {-1.30698039e-08, -2.98577332e-08}});
    std::vector<Vector3d> sp({
        {0.14287043,  0.18905317, -1.59566385},
       {-0.06114921,  0.11447277, -1.60793438},
       {-0.14121952,  0.04381781, -1.6063727},
       {-0.25182638,  0.02916701, -1.59311925}});

    // Compare LL values to equivalent calculations from dials.
    ParameterVector params({1e-3, 2e-3, 3e-3, 4e-3, 5e-3, 6e-3});
    Simple6MosaicityParameterisation model(params);
    MaximumLikelihoodTarget target(model, A, s0, sp, covariances, intensities, miller_indices, mobs);
    double ll = target.log_likelihood();
    std::cout << ll << std::endl;
    EXPECT_NEAR(ll, 5891.998590653, 1e-3);
    ParameterVector params2({2e-3, 3e-3, 4e-3, 5e-3, 6e-3, 7e-3});
    model.set_parameters(params2);
    target.update();
    double ll2 = target.log_likelihood();
    std::cout << ll2 << std::endl;
    EXPECT_NEAR(ll2, 6680.304116342, 1e-3);
}

